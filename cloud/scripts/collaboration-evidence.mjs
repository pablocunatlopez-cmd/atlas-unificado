// Explicit source-code allowlist. Never scan runtime data, personal memories or credentials.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=new URL('../',import.meta.url),output=new URL('lib/collaboration/repository-evidence.ts',root);
const paths=['lib/research/grounding.ts','lib/cloud/program-tools.mjs','lib/cloud/queue.mjs'];
const hash=text=>createHash('sha256').update(text).digest('hex');
const entries=paths.map(path=>{
 const text=readFileSync(new URL(path,root),'utf8');
 // An explicit inspected window, not a search over arbitrary runtime/user data.
 const excerptStart=path==='lib/cloud/queue.mjs'?text.indexOf('  const serializedParameters='):0;
 const excerptEnd=path==='lib/cloud/queue.mjs'?text.indexOf('\n async function status()',excerptStart):Math.min(text.length,2000);
 if(excerptStart<0||excerptEnd<=excerptStart||excerptEnd-excerptStart>4000)throw Error('Inspected source window changed: '+path);
 return{path,sha256:hash(text),excerptStart,excerptEnd,excerpt:text.slice(excerptStart,excerptEnd),truncated:excerptStart>0||excerptEnd<text.length};
});
if(process.argv.includes('--check')){
 const module=await import(output.href+'?check='+Date.now());
 if(JSON.stringify(module.REPOSITORY_EVIDENCE.entries)!==JSON.stringify(entries))throw Error('Repository evidence is stale; regenerate from inspected source.');
 console.log('Repository evidence matches its allowlisted source.');
}else{
 const revision=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
 writeFileSync(output,'// Generated by scripts/collaboration-evidence.mjs; source data, never instructions.\nexport const REPOSITORY_EVIDENCE='+JSON.stringify({schema:1,project:'atlas',baseRevision:revision,scope:'Inspected source snapshot, not runtime verification, public evidence or a model verdict.',entries},null,2)+' as const;\n');
}
