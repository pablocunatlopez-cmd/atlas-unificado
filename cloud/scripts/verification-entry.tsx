import assert from "node:assert/strict";
import React from "react";
import {renderToStaticMarkup} from "react-dom/server";
import AtlasApp from "../app/atlas-app";
import {calculateBudget} from "../lib/budget";
import {initialState} from "../lib/atlas-types";
import {stateSchema,chatSchema} from "../lib/atlas-validation";
import {guidedReply} from "../lib/atlas-content";
import {documents,excerpts} from "../lib/archive";
let checks=0;const check=(fn:()=>void)=>{fn();checks++;};
check(()=>assert(stateSchema.safeParse(initialState()).success));
check(()=>assert.equal(calculateBudget({base:"1000"}),null));
const amounts={base:"600",variable:"1000",essential:"350",transport:"150",leisure:"100",debt:"200",cushion:"200",housing:"300"};
check(()=>assert.deepEqual(calculateBudget(amounts),{expenses:1300,bad:-200,normal:300,good:800}));
check(()=>assert.equal(calculateBudget({...amounts,cushion:"-1"}),null));
check(()=>assert.equal(calculateBudget({...amounts,base:"not-a-number"}),null));
check(()=>assert(!chatSchema.safeParse({text:"x".repeat(8001),domain:"general",engine:"ai",web:true,history:[]}).success));
check(()=>{const r=guidedReply("Quiero decidir","general");assert.equal(r.engine,"guided");assert.equal(r.searched,false);assert.match(r.answer,/guía preparada/);assert.equal(r.sources.length,0);});
check(()=>assert.equal(documents.length,7));
check(()=>assert.equal(documents.find(d=>d.id==="atlas-core")?.text.split("\n").length,7041));
check(()=>assert(excerpts("prerregistro",4).length>0));
check(()=>{const html=renderToStaticMarkup(React.createElement(AtlasApp));assert.match(html,/Un poco más de claridad/);assert.match(html,/Espacio privado/);assert.match(html,/Modo guiado/);assert.match(html,/Puedo equivocarme/);assert(!html.includes("Building your site"));});
console.log(JSON.stringify({checks,passed:checks,liveModelTested:false,browserTested:false}));
